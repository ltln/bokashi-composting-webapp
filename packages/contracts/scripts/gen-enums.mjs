#!/usr/bin/env node
// Generates the tracking enums from packages/contracts/events.json:
//   - apps/api/internal/events/enums_gen.go  (Go constants + Valid())
//   - packages/contracts/ts/events.ts        (TS union types + constants)
//
// No dependencies. Output is deterministic and already gofmt-formatted, so
// running `make gen` twice produces no diff.
//
// Usage: node packages/contracts/scripts/gen-enums.mjs

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const contractsDir = resolve(here, "..");
const repoRoot = resolve(contractsDir, "../..");

const GO_OUT = join(repoRoot, "apps/api/internal/events/enums_gen.go");
const TS_OUT = join(contractsDir, "ts/events.ts");
const HEADER =
  "Code generated by packages/contracts/scripts/gen-enums.mjs from packages/contracts/events.json. DO NOT EDIT.";

const spec = JSON.parse(readFileSync(join(contractsDir, "events.json"), "utf8"));
validate(spec);

const eventTypes = spec.eventTypes;
const targets = spec.featureTargets;
const targetByValue = new Map(targets.map((t) => [t.value, t]));

write(GO_OUT, renderGo());
write(TS_OUT, renderTs());

// ---------------------------------------------------------------------------

function validate(s) {
  const ident = /^[A-Z][A-Za-z0-9]*$/;
  const fail = (msg) => {
    console.error(`events.json: ${msg}`);
    process.exit(1);
  };
  if (!Array.isArray(s.eventTypes) || !Array.isArray(s.featureTargets)) {
    fail("eventTypes and featureTargets must be arrays");
  }
  const seen = new Set();
  for (const t of s.featureTargets) {
    if (!t.value || !ident.test(t.name)) fail(`bad feature target ${JSON.stringify(t)}`);
    if (t.tab !== "setup" && t.tab !== "faq") fail(`target ${t.value}: tab must be "setup" or "faq"`);
    if (seen.has(t.value)) fail(`duplicate target ${t.value}`);
    seen.add(t.value);
  }
  const seenTypes = new Set();
  for (const e of s.eventTypes) {
    if (!/^[a-z0-9_]+$/.test(e.value) || !ident.test(e.name)) fail(`bad event type ${JSON.stringify(e)}`);
    if (seenTypes.has(e.value)) fail(`duplicate event type ${e.value}`);
    seenTypes.add(e.value);
    for (const v of e.targets) if (!seen.has(v)) fail(`event ${e.value}: unknown target ${v}`);
  }
}

function write(path, content) {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content);
  console.log(`wrote ${path.slice(repoRoot.length + 1)}`);
}

function goConst(prefix, name) {
  return `${prefix}${name}`;
}

function renderGo() {
  const evName = (e) => goConst("Event", e.name);
  const tgName = (v) => goConst("Target", targetByValue.get(v).name);
  const pad = (names) => {
    const w = Math.max(...names.map((n) => n.length));
    return (n) => n + " ".repeat(w - n.length);
  };
  const padEv = pad(eventTypes.map(evName));
  const padTg = pad(targets.map((t) => tgName(t.value)));

  const L = [];
  L.push(`// ${HEADER}`, "", "package events", "");
  L.push("// EventType is a web_access_logs.event_type value.");
  L.push("type EventType string", "");
  L.push("// FeatureTarget is a web_access_logs.feature_target value.");
  L.push("type FeatureTarget string", "");
  L.push("// Event types.", "const (");
  for (const e of eventTypes) L.push(`\t${padEv(evName(e))} EventType = ${JSON.stringify(e.value)}`);
  L.push(")", "");
  L.push("// Feature targets.", "const (");
  for (const t of targets) L.push(`\t${padTg(tgName(t.value))} FeatureTarget = ${JSON.stringify(t.value)}`);
  L.push(")", "");
  L.push("// EventTypes lists every event type in contract order.");
  L.push(`var EventTypes = []EventType{${eventTypes.map(evName).join(", ")}}`, "");
  L.push("// FeatureTargets lists every feature target in contract order.");
  L.push(`var FeatureTargets = []FeatureTarget{${targets.map((t) => tgName(t.value)).join(", ")}}`, "");

  L.push("// AllowedTargets returns the feature targets allowed for eventType. It returns");
  L.push("// nil for unknown types and for types that take no target (page_view).");
  L.push("func AllowedTargets(eventType EventType) []FeatureTarget {", "\tswitch eventType {");
  for (const e of eventTypes) {
    if (e.targets.length === 0) continue;
    L.push(`\tcase ${evName(e)}:`);
    L.push(`\t\treturn []FeatureTarget{${e.targets.map(tgName).join(", ")}}`);
  }
  L.push("\t}", "\treturn nil", "}", "");

  L.push('// Tab returns the app tab a target belongs to: "setup", "faq", or "" if unknown.');
  L.push("func (t FeatureTarget) Tab() string {", "\tswitch t {");
  for (const tab of ["setup", "faq"]) {
    const names = targets.filter((t) => t.tab === tab).map((t) => tgName(t.value));
    if (names.length === 0) continue;
    L.push(`\tcase ${names.join(", ")}:`, `\t\treturn ${JSON.stringify(tab)}`);
  }
  L.push("\t}", '\treturn ""', "}", "");

  L.push("// Valid reports whether eventType and target form an allowed combination.");
  L.push('// target must be "" for event types that take no target (page_view).');
  L.push("func Valid(eventType, target string) bool {", "\tswitch EventType(eventType) {");
  for (const e of eventTypes) {
    L.push(`\tcase ${evName(e)}:`);
    if (e.targets.length === 0) {
      L.push('\t\treturn target == ""');
    } else {
      L.push("\t\tswitch FeatureTarget(target) {");
      L.push(`\t\tcase ${e.targets.map(tgName).join(", ")}:`);
      L.push("\t\t\treturn true", "\t\t}");
    }
  }
  L.push("\t}", "\treturn false", "}");
  return L.join("\n") + "\n";
}

function renderTs() {
  const L = [];
  const q = JSON.stringify;
  L.push(`// ${HEADER}`, "");
  L.push("/** Event_Type values (web_access_logs.event_type). */");
  L.push("export const EventType = {");
  for (const e of eventTypes) L.push(`  /** ${e.description} */`, `  ${e.name}: ${q(e.value)},`);
  L.push("} as const;");
  L.push("export type EventType = (typeof EventType)[keyof typeof EventType];", "");

  L.push("/** Feature_Target values (web_access_logs.feature_target). */");
  L.push("export const FeatureTarget = {");
  for (const t of targets) L.push(`  ${t.name}: ${q(t.value)},`);
  L.push("} as const;");
  L.push("export type FeatureTarget = (typeof FeatureTarget)[keyof typeof FeatureTarget];", "");

  L.push("/** Every event type, in contract order. */");
  L.push("export const EVENT_TYPES: readonly EventType[] = [");
  for (const e of eventTypes) L.push(`  ${q(e.value)},`);
  L.push("];", "");

  L.push("/** Every feature target, in contract order. */");
  L.push("export const FEATURE_TARGETS: readonly FeatureTarget[] = [");
  for (const t of targets) L.push(`  ${q(t.value)},`);
  L.push("];", "");

  L.push("/** Targets allowed per event type. An empty list means the event takes no target. */");
  L.push("export const ALLOWED_TARGETS: { readonly [K in EventType]: readonly FeatureTarget[] } = {");
  for (const e of eventTypes) L.push(`  ${e.value}: [${e.targets.map(q).join(", ")}],`);
  L.push("};", "");

  L.push("/** Which app tab each target belongs to (used to colour admin charts). */");
  L.push('export const FEATURE_TARGET_TAB: { readonly [K in FeatureTarget]: "setup" | "faq" } = {');
  for (const t of targets) L.push(`  ${/^[A-Za-z_]\w*$/.test(t.value) ? t.value : q(t.value)}: ${q(t.tab)},`);
  L.push("};", "");

  L.push("/** Typed (eventType, featureTarget) pairs accepted by the API. */");
  L.push("export type TrackedEvent =");
  eventTypes.forEach((e, i) => {
    const end = i === eventTypes.length - 1 ? ";" : "";
    const target = e.targets.length === 0 ? "undefined" : e.targets.map(q).join(" | ");
    L.push(`  | { eventType: ${q(e.value)}; featureTarget?: ${target} }${end}`);
  });
  L.push("");

  L.push("/** Reports whether eventType/featureTarget form an allowed combination. */");
  L.push("export function isValidEvent(eventType: string, featureTarget?: string | null): boolean {");
  L.push("  if (!Object.prototype.hasOwnProperty.call(ALLOWED_TARGETS, eventType)) return false;");
  L.push("  const allowed = ALLOWED_TARGETS[eventType as EventType] as readonly string[];");
  L.push("  if (allowed.length === 0) return featureTarget == null || featureTarget === \"\";");
  L.push("  return featureTarget != null && allowed.includes(featureTarget);");
  L.push("}");
  return L.join("\n") + "\n";
}
